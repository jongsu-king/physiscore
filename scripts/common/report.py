"""Markdown report writer shared by the analysis tools.

A report is a folder-friendly Markdown file (tables as pipe tables, the
figure saved next to it as PNG at 300 dpi) that can be pasted into a lab
notebook or converted with pandoc. It records the program version, the
date, the input files and every table the tool shows, so a number in a
manuscript can be traced back to its analysis.
"""
from __future__ import annotations

import datetime as _dt
import os
import subprocess
import sys
from typing import Iterable, List, Optional, Sequence, Tuple, Union

import numpy as np
import pandas as pd

Section = Tuple[str, Union[pd.DataFrame, str, dict, Sequence[Sequence]]]


def _version() -> str:
    try:
        from Physiscore_Launcher import APP_VERSION
        return APP_VERSION
    except Exception:
        return ""


def _fmt(v) -> str:
    if v is None:
        return ""
    if isinstance(v, float):
        if not np.isfinite(v):
            return ""
        if v != 0 and (abs(v) < 1e-3 or abs(v) >= 1e5):
            return f"{v:.4g}"
        return f"{v:.4f}".rstrip("0").rstrip(".") if abs(v) < 100 else f"{v:.2f}"
    return str(v)


def dataframe_to_markdown(df: pd.DataFrame, index: bool = False, max_rows: Optional[int] = None) -> str:
    if df is None or df.empty:
        return "_(empty)_\n"
    d = df.copy()
    if index:
        d = d.reset_index()
    if max_rows is not None and len(d) > max_rows:
        d = d.head(max_rows)
    cols = [str(c) for c in d.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join(["---"] * len(cols)) + "|"]
    for _, row in d.iterrows():
        lines.append("| " + " | ".join(_fmt(v).replace("|", "/") for v in row.tolist()) + " |")
    return "\n".join(lines) + "\n"


def dict_to_markdown(d: dict) -> str:
    lines = ["| Quantity | Value |", "|---|---|"]
    for k, v in d.items():
        lines.append(f"| {k} | {_fmt(v)} |")
    return "\n".join(lines) + "\n"


def write_markdown_report(path: str, title: str, sections: Iterable[Section], figure=None,
                          inputs: Optional[Sequence[str]] = None, notes: Optional[str] = None,
                          figure_dpi: int = 300) -> str:
    """Write the report to `path` (.md). The figure, if any, is saved beside it
    as <stem>.png in publication style and linked from the report. Returns
    the path written."""
    path = os.path.abspath(path)
    stem = os.path.splitext(path)[0]
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    out: List[str] = [f"# {title}", ""]
    out.append(f"Generated by Physiscore {_version()} on {_dt.datetime.now():%Y-%m-%d %H:%M}.")
    out.append("")
    if inputs:
        out.append("**Input**")
        out.append("")
        for p in inputs:
            out.append(f"- `{p}`")
        out.append("")
    fig_path = None
    if figure is not None:
        fig_path = stem + ".png"
        try:
            from scripts.common.analysis_shell import _publication_copy
            pub = _publication_copy(figure) or figure
            pub.savefig(fig_path, dpi=figure_dpi, facecolor="white", bbox_inches="tight")
            if pub is not figure:
                import matplotlib.pyplot as _plt
                _plt.close(pub)
        except Exception:
            try:
                figure.savefig(fig_path, dpi=figure_dpi, bbox_inches="tight")
            except Exception:
                fig_path = None
    if fig_path:
        out.append(f"![figure]({os.path.basename(fig_path)})")
        out.append("")
    for heading, content in sections:
        out.append(f"## {heading}")
        out.append("")
        if isinstance(content, pd.DataFrame):
            out.append(dataframe_to_markdown(content))
        elif isinstance(content, dict):
            out.append(dict_to_markdown(content))
        elif isinstance(content, str):
            out.append(content.rstrip() + "\n")
        else:
            out.append(dataframe_to_markdown(pd.DataFrame(list(content))))
        out.append("")
    if notes:
        out.append("## Notes")
        out.append("")
        out.append(notes.rstrip() + "\n")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
    return path


def open_path(path: str) -> None:
    """Open a file or folder with the system default application."""
    if sys.platform == "win32":
        os.startfile(path)  # type: ignore[attr-defined]
    elif sys.platform == "darwin":
        subprocess.Popen(["open", path])
    else:
        subprocess.Popen(["xdg-open", path])


def ask_report_path(parent, default_name: str) -> Optional[str]:
    from tkinter import filedialog
    return filedialog.asksaveasfilename(parent=parent, title="Save report", defaultextension=".md",
                                        initialfile=default_name,
                                        filetypes=[("Markdown report", "*.md"), ("All files", "*.*")]) or None
